CREATE TABLE USERS_ADDRESS (
    ID NUMERIC NOT NULL,
    ADDRESS VARCHAR(500) NOT NULL,
    POSTAL_CODE VARCHAR(10) NOT NULL,

    CONSTRAINT PK_USERS_ADDRESS PRIMARY KEY (ID),
    CONSTRAINT FK_USERS_ADDRESS_USERS FOREIGN KEY (USERS_ID) REFERENCES USERS(ID)
);

CREATE SEQUENCE users_address_seq START WITH 1 INCREMENT BY 1 NOCACHE;