CREATE TABLE SHAKHS_ADDRESS (
    ID NUMBER NOT NULL,
    SHAKHS_ID NUMBER NOT NULL,
    ADDRESS VARCHAR2(500),
    POSTAL_CODE VARCHAR2(20),
    CONSTRAINT PK_SHAKHS_ADDRESS PRIMARY KEY (ID),
    CONSTRAINT FK_SHAKHS_ADDRESS_SHAKHS
        FOREIGN KEY (SHAKHS_ID)
        REFERENCES SYSTEM.SHAKHS(ID)
);